#!/usr/bin/env node
// BSAHI — 21 Identity Agent
// Audits the public identity surface: NIP-05 resolution, feed validity, and
// old-key residue across publicly served files. Exits non-zero on violations.
var path = require('path');
var fs = require('fs');

var REPO = path.resolve(__dirname, '..', '..');
var CURRENT_PUBKEY = '44744d037e50a4f3bc6b44b9ca7c5a3f52e68b0f70789696ccb7e28e274d2d61';
var OLD_PUBKEY = 'b4bc93933169b6a288d08a2599832f05ff6b3a72a801a60b5266a29295bcaedc';
var OUT = path.join(REPO, 'reports', 'data-engineering', 'identity-audit-' + new Date().toISOString().slice(0, 10) + '.md');

function loadJson(p, fb) { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { return fb; } }

function run() {
  var violations = [];
  var notes = [];

  // 1. NIP-05: .well-known/nostr.json must exist at root and map _ to current pubkey
  var wkPath = path.join(REPO, '.well-known', 'nostr.json');
  if (fs.existsSync(wkPath)) {
    var wk = loadJson(wkPath, null);
    if (!wk) { violations.push('NIP-05 file exists but unparseable'); }
    else if (!wk.names || wk.names._ !== CURRENT_PUBKEY) {
      violations.push('NIP-05 _ maps to ' + (wk.names && wk.names._ ? wk.names._ : 'MISSING') + ' — expected current pubkey');
    } else {
      notes.push('NIP-05 _@bitcoinsahi.com -> current pubkey OK');
    }
  } else {
    violations.push('.well-known/nostr.json missing at root (NIP-05 broken)');
  }

  // 2. Feed validity: all guids are 64-hex (no >undefined)
  var feedPath = path.join(REPO, 'feed.xml');
  if (fs.existsSync(feedPath)) {
    var feed = fs.readFileSync(feedPath, 'utf8');
    var guids = feed.match(/<guid>([^<]+)<\/guid>/g) || [];
    var bad = guids.filter(function(g) { return !/^<guid>[0-9a-f]{64}<\/guid>$/.test(g); });
    if (bad.length) violations.push(bad.length + ' feed guids are not 64-hex (broken entries)');
    else notes.push('Feed guids valid (' + guids.length + ' items)');
  } else {
    violations.push('feed.xml missing at root');
  }

  // 3. Old pubkey residue across publicly served files
  var targets = [
    path.join(REPO, 'reports', 'marketing', 'distribution-report.md'),
    // post-report.md moved to archive/ 2026-08-14 (U4: persona framing retired).
    path.join(REPO, 'reports', 'marketing', 'archive', 'post-report.md'),
    path.join(REPO, '.well-known', 'nostr.json'),
    path.join(REPO, 'docs', '.well-known', 'nostr.json')
  ];
  targets.forEach(function(f) {
    if (fs.existsSync(f)) {
      var content = fs.readFileSync(f, 'utf8');
      if (content.indexOf(OLD_PUBKEY) !== -1) {
        violations.push('OLD pubkey residue in ' + path.relative(REPO, f));
      }
    }
  });

  // 4. index.html references current pubkey if any (team.html removed from public site)
  ['index.html'].forEach(function(f) {
    var p = path.join(REPO, f);
    if (fs.existsSync(p)) {
      var c = fs.readFileSync(p, 'utf8');
      if (c.indexOf(OLD_PUBKEY) !== -1) violations.push('OLD pubkey residue in ' + f);
    }
  });

  var lines = ['# Identity Audit — ' + new Date().toISOString().slice(0, 10), ''];
  lines.push('## Current pubkey: ' + CURRENT_PUBKEY.slice(0, 16) + '...');
  lines.push('## Result: ' + (violations.length ? 'VIOLATIONS (' + violations.length + ')' : 'CLEAN'));
  lines.push('');
  if (violations.length) { lines.push('### Violations'); violations.forEach(function(v) { lines.push('- ' + v); }); }
  if (notes.length) { lines.push('### Notes'); notes.forEach(function(n) { lines.push('- ' + n); }); }
  lines.push('');
  lines.push('_Generated by 21-identity-agent._');
  try {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, lines.join('\n'));
  } catch (e) {}

  if (require.main === module) {
    console.log(lines.join('\n'));
    process.exit(violations.length ? 1 : 0);
  }
  return { violations: violations, notes: notes, out: OUT };
}

if (require.main === module) { run(); }
module.exports = { run: run };
